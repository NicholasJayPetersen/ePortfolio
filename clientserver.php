<h2>What is the client/server model?</h2>
	<p>The idea behind the client/server model is that certain machines will act a a client machine, or a "host" machine, while other computers will act as a server machine that perform tasks for the clients. A client device will send a request to a server machine to process. The server machine will then perform the requested action for the client and return the results. Server machines typically do not make any requests of their own. They only exist to "serve" others. One example of this would be a DHCP server handing out IP addresses. This servers main task is to listen for other computers that want to access a particular network. When it hears a request to communicate it will send back a designated address for that device and various other metadata. Say you were just issued a new laptop at work, and you need to connect to the building wifi for the first time. You would attempt to join the network. Behind the scenes the laptop will send a request to the DHCP server. The server will answer your computer with an IP address, DNS, and other metadata. Now you can surf the internet.</p>
	
	<h2>Advantages of the client/server model</h2>
	
	<p>Several major advantages of the client/server model are:</p>
	
	<ol>
		<li>Scalability for future growth</li>
		<li>Consolidation of hardware and services saves physical space</li>
		<li>Even distribution of resources among client devices</li>
		<li>Centralized management of system services</li>
	</ol>
	
