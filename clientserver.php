	<h2>Examples of TCP/IP protocols</h2>
		<ul>
			<li>FTP: File Transfer Protocol moves files between the client and the server</li>
			<li>HTTP: Hyper Text Transfer Protocol facilitates requests for web pages between the client and server</li>
			<li>HTTPS: Hyper Text Transfer Protocol Secure does the same as HTTP except under a layer of encryption</li>
			<li>DHCP: Dynamic Host Configuration Protocol assigns a client device a network configuration (IP, subnet, gateway, DNS, etc.).</li>
			<li>SMTP: Simple Mail Transfer Protocol defines the rules for transmission of emails between the client and mail server, and from server to server.</li>
		</ul>
	
	<h2>Examples of network utilities and services</h2>
